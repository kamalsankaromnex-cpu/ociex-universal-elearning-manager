// Use Prisma's official WASM migration engine and the same PostgreSQL adapter as the app.
// This retains Prisma migration history and works without a native-engine download.
import { readFile, writeFile, readdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve, dirname } from "node:path";
import { PrismaPg } from "@prisma/adapter-pg";
import { bindMigrationAwareSqlAdapterFactory } from "@prisma/driver-adapter-utils";
import * as runtime from "@prisma/schema-engine-wasm/schema_engine_bg";
const require = createRequire(import.meta.url);
const wasmPath = resolve(
  dirname(require.resolve("@prisma/schema-engine-wasm/schema_engine_bg")),
  "schema_engine_bg.wasm",
);
const wasmModule = new WebAssembly.Module(await readFile(wasmPath));
const instance = new WebAssembly.Instance(wasmModule, {
  "./schema_engine_bg.js": runtime,
});
runtime.__wbg_set_wasm(instance.exports);
instance.exports.__wbindgen_start();
const schemaPath = resolve("prisma/schema.prisma");
const schema = await readFile(schemaPath, "utf8");
const engine = await runtime.SchemaEngine.new(
  { datamodels: [[schemaPath, schema]] },
  () => {},
  bindMigrationAwareSqlAdapterFactory(
    new PrismaPg({ connectionString: process.env.DATABASE_URL }),
  ),
);
const filters = { externalTables: [], externalEnums: [] };
try {
  if (process.argv.includes("--generate-initial")) {
    const diff = await engine.diff({
      from: { tag: "empty" },
      to: {
        tag: "schemaDatamodel",
        files: [{ path: schemaPath, content: schema }],
      },
      script: true,
      exitCode: null,
      filters,
    });
    await writeFile(
      "prisma/migrations/20261104000000_init/migration.sql",
      diff.stdout,
    );
    console.log("Initial migration generated by Prisma WASM.");
  } else {
    const baseDir = resolve("prisma/migrations");
    const entries = await readdir(baseDir, { withFileTypes: true });
    const migrationDirectories = await Promise.all(
      entries
        .filter((e) => e.isDirectory())
        .sort((a, b) => a.name.localeCompare(b.name))
        .map(async (e) => ({
          path: e.name,
          migrationFile: {
            path: "migration.sql",
            content: {
              tag: "ok",
              value: await readFile(
                resolve(baseDir, e.name, "migration.sql"),
                "utf8",
              ),
            },
          },
        })),
    );
    console.log(
      await engine.applyMigrations({
        migrationsList: {
          baseDir,
          lockfile: {
            path: "migration_lock.toml",
            content: await readFile(
              resolve(baseDir, "migration_lock.toml"),
              "utf8",
            ),
          },
          shadowDbInitScript: "",
          migrationDirectories,
        },
        filters,
      }),
    );
  }
} finally {
  engine.free();
}
